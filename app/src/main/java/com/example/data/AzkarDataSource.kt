        return allAzkar.filter { it.category == category }
    }

    fun search(query: String): List<ZikrItem> {
        val q = query.trim().lowercase()
        return allAzkar.filter {
            it.text.contains(q, ignoreCase = true) ||
            it.category.contains(q, ignoreCase = true) ||
            it.virtue.contains(q, ignoreCase = true)
        }
    }
